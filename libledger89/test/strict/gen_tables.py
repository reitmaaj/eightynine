def part_header_regions(prefix):
    return [
        (prefix, "header.magic", 0, 8),
        (prefix, "header.uuid", 8, 16),
        (prefix, "header.file_id", 24, 8),
        (prefix, "header.revision", 32, 8),
        (prefix, "header.first", 40, 8),
        (prefix, "header.version", 48, 4),
        (prefix, "header.reserved", 52, 4),
        (prefix, "header.crc", 56, 4),
        (prefix, "header.reserved2", 60, 4),
    ]


def marker_regions(prefix, index, offset):
    return [
        (prefix, "marker[%d].magic" % index, offset, 8),
        (prefix, "marker[%d].uuid" % index, offset + 8, 16),
        (prefix, "marker[%d].file_id" % index, offset + 24, 8),
        (prefix, "marker[%d].revision" % index, offset + 32, 8),
        (prefix, "marker[%d].end" % index, offset + 40, 8),
        (prefix, "marker[%d].version" % index, offset + 48, 4),
        (prefix, "marker[%d].crc" % index, offset + 52, 4),
        (prefix, "marker[%d].trailer" % index, offset + 56, 8),
    ]


def batch_size(sizes):
    return 32 + sum(4 + size + 4 for size in sizes) + 24


def batch_regions(prefix, index, offset, first, sizes):
    regions = [
        (prefix, "batch[%d].magic" % index, offset, 4),
        (prefix, "batch[%d].count" % index, offset + 4, 4),
        (prefix, "batch[%d].first" % index, offset + 8, 8),
        (prefix, "batch[%d].bytes" % index, offset + 16, 8),
        (prefix, "batch[%d].header_crc" % index, offset + 24, 4),
        (prefix, "batch[%d].reserved" % index, offset + 28, 4),
    ]
    position = offset + 32
    for record, size in enumerate(sizes):
        regions.append((prefix, "batch[%d].record[%d].length" % (index, record),
                        position, 4))
        regions.append((prefix, "batch[%d].record[%d].payload" % (index, record),
                        position + 4, size))
        regions.append((prefix, "batch[%d].record[%d].crc" % (index, record),
                        position + 4 + size, 4))
        position += 4 + size + 4
    footer = offset + batch_size(sizes) - 24
    regions += [
        (prefix, "batch[%d].footer_magic" % index, footer, 4),
        (prefix, "batch[%d].footer_count" % index, footer + 4, 4),
        (prefix, "batch[%d].footer_last" % index, footer + 8, 8),
        (prefix, "batch[%d].footer_crc" % index, footer + 16, 4),
        (prefix, "batch[%d].footer_reserved" % index, footer + 20, 4),
    ]
    return regions, footer + 24


def part_regions(prefix, markers, batches, sealed):
    """markers: list of marker end values; batches: list of (first, sizes)."""
    regions = part_header_regions(prefix)
    offset = 64
    for index, end in enumerate(markers):
        regions += marker_regions(prefix, index, offset)
        offset += 64
        if index < len(batches):
            first, sizes = batches[index]
            batch, offset = batch_regions(prefix, index, offset, first, sizes)
            regions += batch
    if sealed:
        regions += [
            (prefix, "sealed.magic", offset, 8),
            (prefix, "sealed.uuid", offset + 8, 16),
            (prefix, "sealed.file_id", offset + 24, 8),
            (prefix, "sealed.first", offset + 32, 8),
            (prefix, "sealed.end", offset + 40, 8),
            (prefix, "sealed.records", offset + 48, 8),
            (prefix, "sealed.digest", offset + 56, 4),
            (prefix, "sealed.crc", offset + 60, 4),
        ]
    return regions


def manifest_regions(sealed_count):
    regions = [
        ("MANIFEST", "magic", 0, 8),
        ("MANIFEST", "generation", 8, 8),
        ("MANIFEST", "uuid", 16, 16),
        ("MANIFEST", "revision", 32, 8),
        ("MANIFEST", "first", 40, 8),
        ("MANIFEST", "sealed_count", 48, 4),
        ("MANIFEST", "version", 52, 4),
        ("MANIFEST", "header_crc", 56, 4),
        ("MANIFEST", "reserved", 60, 4),
    ]
    offset = 64
    for index in range(sealed_count):
        regions.append(("MANIFEST", "sealed[%d]" % index, offset, 24))
        offset += 24
    regions.append(("MANIFEST", "active", offset, 16))
    offset += 16
    regions.append(("MANIFEST", "crc", offset, 4))
    return regions


