def fixture_regions(fixture):
    spec = FIXTURES[fixture]
    regions = [
        ("CURRENT", "CURRENT", "magic", 0, 8),
        ("CURRENT", "CURRENT", "generation", 8, 8),
        ("CURRENT", "CURRENT", "version", 16, 4),
        ("CURRENT", "CURRENT", "crc", 20, 4),
        ("CURRENT", "CURRENT", "reserved", 24, 8),
    ]
    for kind, region, offset, size in manifest_regions(spec["manifest_sealed"]):
        regions.append((kind, None, region, offset, size))
    for name, kind, markers, batches, sealed, _size in spec["parts"]:
        for _kind, region, offset, size in part_regions(name, markers, batches,
                                                        sealed):
            regions.append((kind, name, region, offset, size))
    return regions


def classify(file_kind, region):
    if region == "header.reserved":
        return ("open", ("ECORRUPT",))
    if file_kind == "MANIFEST" and region == "reserved":
        return ("open", ("ECORRUPT",))
    if region.endswith("reserved") or region.endswith("reserved2"):
        return ("open", ("OK",))
    if file_kind in ("CURRENT", "MANIFEST"):
        if region == "version":
            return ("open", ("EFORMAT",))
        return ("open", ("ECORRUPT",))
    if region == "header.version":
        return ("open", ("ECORRUPT",))
    if region.startswith("marker["):
        if region.endswith(".trailer"):
            return ("open", ("OK", "ECORRUPT"))
        if file_kind == "part.sealed":
            return ("open", ("ECORRUPT",))
        return ("open", ("OK", "ECORRUPT"))
    if region.startswith("batch[") and ".record[" in region:
        if (region.endswith(".payload") or region.endswith(".crc")
                or region.endswith(".length")):
            return ("read", ("ECORRUPT",))
    if ".footer_crc" in region:
        return ("verify", ("ECORRUPT",))
    if region.startswith("sealed."):
        return ("open", ("ECORRUPT",))
    return ("open", ("ECORRUPT",))


def corrupt_rows():
    rows = []
    for fixture in FIXTURES:
        for file_kind, file_name, region, offset, size in fixture_regions(fixture):
            check, allowed = classify(file_kind, region)
            for relative in range(size):
                for spec_value in VALUE_SPECS:
                    name = "corrupt.%s.%s.%s.%d.%s" % (
                        fixture,
                        file_kind.replace(".", "_"),
                        region.replace("[", "_").replace("]", "").replace(".", "_"),
                        relative,
                        spec_value.replace(":", "_"),
                    )
                    rows.append(row(name, fixture, file_kind, file_name, region,
                                    offset + relative, spec_value, check,
                                    allowed))
    return rows


def truncate_file_rows():
    rows = []
    for fixture, spec in FIXTURES.items():
        for length in range(0, 32):
            rows.append(row("trunc.%s.CURRENT.%d" % (fixture, length), fixture,
                            "CURRENT", "CURRENT", length,
                            ("ECORRUPT", "EFORMAT", "ENOENT")))
        for length in range(0, spec["manifest_size"]):
            rows.append(row("trunc.%s.MANIFEST.%d" % (fixture, length),
                            fixture, "MANIFEST", None, length,
                            ("ECORRUPT", "EFORMAT", "ENOENT")))
        for name, kind, _markers, _batches, sealed, size in spec["parts"]:
            allowed = (("ECORRUPT", "EFORMAT") if sealed
                       else ("OK", "ECORRUPT", "EFORMAT"))
            for length in range(0, size):
                rows.append(row("trunc.%s.%s.%s.%d" % (fixture, kind, name,
                                                       length),
                                fixture, kind, name, length, allowed))
    return rows


