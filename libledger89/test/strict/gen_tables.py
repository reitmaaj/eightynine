def open_rows():
    rows = []
    flag_values = list(range(0, 256)) + OPEN_SPECIAL_FLAGS
    for flags in flag_values:
        for scenario in ("fresh", "existing", "missing"):
            name = "open.flags.%#x.%s" % (flags, scenario)
            rows.append(row(name, flags, scenario, open_expect(flags, scenario)))
    return rows


def open_expect(flags, scenario):
    # Unknown high bits are ignored: the contract constrains only the four
    # documented flags (RDONLY/RDWR/CREATE/EXCL).
    rdonly = (flags & 0x0001) != 0
    rdwr = (flags & 0x0002) != 0
    create = (flags & 0x0004) != 0
    excl = (flags & 0x0008) != 0
    if rdonly == rdwr:
        return "EINVAL"
    if create and not rdwr:
        return "EINVAL"
    if excl and not create:
        return "EINVAL"
    if scenario == "fresh":
        if not create:
            return "ENOENT"
        return "OK"
    if scenario == "existing":
        if excl:
            return "EEXIST"
        return "OK"
    if not create:
        return "ENOENT"
    return "OK"


def append_rows():
    rows = []
    for size in PAYLOAD_SIZES:
        for count in (1, 2, 4, 8):
            name = "append.size.%d.count.%d" % (size, count)
            sizes = tuple([size] * count)
            expect = append_expect(sizes)
            rows.append(row(name, sizes, count, expect, None, None,
                            1 if expect == "OK" else None,
                            1 + count if expect == "OK" else None))
    specials = [
        ("append.zero_count", (1, 2), 0, "EINVAL"),
        ("append.null_array", (1, 2), 2, "EINVAL"),
        ("append.null_data_nonzero", (1, 2), 2, "EINVAL"),
        ("append.count_over_u32", (1,), UINT32_MAX + 1, "ERANGE"),
        ("append.huge_size_null", (0x7FFFFFFFFFFFFFFF,), 1, "ERANGE"),
        ("append.size_zero_null_ok", (0, 0), 2, "OK"),
        ("append.mixed_valid", (0, 1, 0, 7), 4, "OK"),
    ]
    for name, sizes, count, expect in specials:
        null_array = name == "append.null_array"
        null_data = 0 if name in ("append.null_data_nonzero",
                                  "append.huge_size_null") else None
        first = 1 if expect == "OK" else None
        end = 1 + count if expect == "OK" else None
        rows.append(row(name, tuple(sizes), count, expect, null_array,
                        null_data, first, end))
    return rows


def append_expect(sizes):
    if any(size > MAX_RECORD for size in sizes):
        return "ERANGE"
    return "OK"


FIXTURE_ABC = (b"", b"a", b"hello", b"0123456789")
FIXTURE_MIXED = (b"x", b"", b"yz", b"", b"tail")


def read_rows():
    rows = []
    fixture = FIXTURE_ABC
    indices = [0, 1, 2, 3, 4, 5, 6, 7, UINT64_MAX]
    capacities = list(range(0, 17)) + [31, 32, 63, 64, 65, 127, 128]
    for index in indices:
        for capacity in capacities:
            for null_buffer in (False, True):
                expect, size = read_expect(fixture, index, capacity, null_buffer)
                name = "read.idx.%d.cap.%d.null.%d" % (
                    index, capacity, int(null_buffer))
                rows.append(row(name, "abc", index, capacity, null_buffer,
                                expect, size))
    return rows


def read_expect(fixture, index, capacity, null_buffer):
    first = 1
    end = first + len(fixture)
    if index < first:
        return "EGONE", None
    if index >= end:
        return "ENOENT", None
    size = len(fixture[index - first])
    if null_buffer:
        return "OK", size
    if capacity < size:
        return "ETOOSMALL", size
    return "OK", size


def iter_rows():
    rows = []
    fixture = FIXTURE_MIXED
    starts = [0, 1, 2, 3, 4, 5, 6, 7, UINT64_MAX]
    capacities = list(range(0, 17)) + [31, 32, 63, 64]
    for start in starts:
        for capacity in capacities:
            for null_buffer in (False, True):
                expect = iter_expect(fixture, start)
                name = "iter.from.%d.cap.%d.null.%d" % (
                    start, capacity, int(null_buffer))
                rows.append(row(name, "mixed", start, capacity, null_buffer,
                                expect))
    return rows


def iter_expect(fixture, start):
    first = 1
    end = first + len(fixture)
    if start < first:
        return "EGONE"
    if start > end:
        return "ERANGE"
    return "OK"


def truncate_rows():
    rows = []
    setups = ("clean3", "clean1", "pruned")
    positions = list(range(0, 9)) + [0x100000000, UINT64_MAX]
    for setup in setups:
        for position in positions:
            name = "truncate.%s.from.%d" % (setup, position)
            rows.append(row(name, setup, position,
                            truncate_expect(setup, position)))
    return rows


def truncate_expect(setup, position):
    if setup == "clean3":
        first, end = 1, 4
    elif setup == "clean1":
        first, end = 1, 2
    else:
        first, end = 4, 5
    if position < first:
        return "EGONE"
    if position > end:
        return "ERANGE"
    return "OK"


def prune_rows():
    rows = []
    setups = ("rotated3", "dirty", "single")
    requests = list(range(0, 12)) + [0x100000000, UINT64_MAX]
    for setup in setups:
        for request in requests:
            name = "prune.%s.req.%d" % (setup, request)
            rows.append(row(name, setup, request, prune_expect(setup, request)))
    return rows


def prune_expect(setup, request):
    if setup == "rotated3":
        stable = 7
    elif setup == "dirty":
        stable = 4
    else:
        stable = 2
    if request > stable:
        return "EUNSTABLE"
    return "OK"


def strerror_rows():
    rows = []
    values = (list(range(-64, 33))
              + [1000, 0x7FFFFFFF, -0x80000000])
    for value in values:
        rows.append(row("strerror.%d" % value, value))
    return rows


def u64_rows():
    rows = []
    for a in BOUNDARY_VALUES:
        for b in BOUNDARY_VALUES:
            if a < b:
                sign = -1
            elif a > b:
                sign = 1
            else:
                sign = 0
            rows.append(row("u64.cmp.%d.%d" % (a, b), a, b, sign))
    return rows


