#!/usr/bin/env python3
"""Deterministic generator for the strict-suite case tables.

Run via `just gen-strict-tables`; the committed output under test/strict/
is the source of truth. Every emitted row is executed by a case module in
the fast, full, or long tier as documented in the table's header.
"""

import os

HERE = os.path.dirname(os.path.abspath(__file__))
HEADER = "# Generated by gen_tables.py; do not edit by hand.\n"

UINT32_MAX = 0xFFFFFFFF
UINT64_MAX = 0xFFFFFFFFFFFFFFFF
MAX_RECORD = 16777216


def row(*fields):
    return "    (%s),\n" % ", ".join(repr(field) for field in fields)


def emit(filename, header, sections):
    path = os.path.join(HERE, filename)
    with open(path, "w") as handle:
        handle.write(HEADER)
        handle.write(header)
        for name, rows in sections:
            handle.write("\n%s = [\n" % name)
            for line in rows:
                handle.write(line)
            handle.write("]\n")
    return path


